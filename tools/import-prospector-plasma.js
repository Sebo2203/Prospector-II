// Original atlas combat art, large asteroids and nebula art; see docs/art-direction.md.
const fs=require('node:fs'),path=require('node:path');
const {readBitmap,extractFrame,encodeFrame}=require('./import-prospector-ships.js');
const root=path.resolve(__dirname,'..');
function combatFrame(bitmap,col,row){
  const pixels=new Uint8Array(24*24*4);
  for(let y=0;y<24;y++)for(let x=0;x<24;x++){
    const source=((row*24+y)*bitmap.width+col*24+x)*4,dest=(y*24+x)*4;
    const rgba=bitmap.pixels.subarray(source,source+4);
    // The original transparent blit uses exact magenta. Preserve every other source pixel.
    if(rgba[0]!==255 || rgba[1]!==0 || rgba[2]!==255)pixels.set(rgba,dest);
  }
  return pixels;
}
function plasmaFrame(bitmap,index){return combatFrame(bitmap,index,5);}
function generatePlasmaAssets(){
  const bitmap=readBitmap(fs.readFileSync(path.join(root,'art/source/prospector/space.bmp'))),sprites={};
  if(bitmap.width!==384 || bitmap.height!==144)throw Error('Unexpected original space atlas dimensions');
  for(let index=0;index<4;index++)sprites['combat_plasma_'+index]='data:image/png;base64,'+encodeFrame(plasmaFrame(bitmap,index)).toString('base64');
  [[11,4],[0,2],[1,2],[3,2]].forEach(([col,row],index)=>{
    sprites['combat_asteroid_'+index]='data:image/png;base64,'+encodeFrame(extractFrame(bitmap,col,row)).toString('base64');
  });
  for(const shape of ['2x1','1x2','2x2']){
    const file=path.join(root,'art/source/generated/combat-asteroids-v1/asteroid-'+shape+'.png');
    sprites['combat_asteroid_large_'+shape]='data:image/png;base64,'+fs.readFileSync(file).toString('base64');
  }
  sprites.combat_nebula_cloud='data:image/png;base64,'+fs.readFileSync(path.join(root,'art/source/generated/nebula-cloud-v2/cloud.png')).toString('base64');
  return '// Generated by tools/import-prospector-plasma.js. Atlas and generated combat art: docs/art-direction.md.\n'+
    'const COMBAT_SPRITES_B64 = '+JSON.stringify(sprites,null,2)+';\n';
}
if(require.main===module){
  const output=path.join(root,'src/assets/combat-sprites.js'),source=generatePlasmaAssets();
  if(process.argv.includes('--check')){
    if(fs.readFileSync(output,'utf8').replace(/\r\n/g,'\n')!==source)throw Error('Plasma assets are out of date');
    console.log('Combat sprites match the retained atlas and generated art inputs.');
  }else{fs.writeFileSync(output,source);console.log('Imported atlas combat sprites, large asteroids and approved pixel nebula.');}
}
module.exports={combatFrame,plasmaFrame,generatePlasmaAssets};
