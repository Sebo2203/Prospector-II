function verifyAudio(bytes,entry){
  const sha=crypto.createHash('sha1').update('blob '+bytes.length+'\0').update(bytes).digest('hex');
  if(sha!==entry.sha)throw Error('Original audio hash mismatch: '+entry.file);
  if(bytes.toString('ascii',0,4)!=='RIFF'||bytes.toString('ascii',8,12)!=='WAVE')throw Error('Expected WAV: '+entry.file);
}
function generateAudioAssets(){
  const catalog=JSON.parse(fs.readFileSync(path.join(root,'art/source/audio/catalog.json'),'utf8')),samples={};
  for(const entry of catalog){
    if(samples[entry.id] || !/^art\/source\/[a-zA-Z0-9_./-]+\.(mp3|wav)$/.test(entry.path) || entry.path.split('/').includes('..'))throw Error('Invalid audio catalog entry');
    const bytes=fs.readFileSync(path.join(root,entry.path));
    if(crypto.createHash('sha256').update(bytes).digest('hex')!==entry.sha256 || bytes.length!==entry.bytes)throw Error('Audio hash mismatch: '+entry.id);
    if(entry.id==='crewPain')verifyAudio(bytes,ORIGINAL_AUDIO.find(e=>e.id==='PAIN'));
    samples[entry.id]='data:audio/'+(entry.path.endsWith('.wav')?'wav':'mpeg')+';base64,'+bytes.toString('base64');
  }
  return '// Generated by tools/import-prospector-audio.js; sources and selections: art/source/audio/catalog.json.\n'+
    'const AUDIO_SAMPLES = '+JSON.stringify(samples,null,2)+';\n';
}
if(require.main===module){
  const target=path.join(root,'src/assets/audio-samples.js'),generated=generateAudioAssets();
  if(process.argv.includes('--check')){
    if(fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==generated)throw Error('Embedded original audio is out of date');
    console.log('Embedded samples match the verified audio catalog.');
  }else{fs.writeFileSync(target,generated);console.log('Embedded the selected sound recordings.');}
}
