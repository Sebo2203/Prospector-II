  assert.deepEqual(errors,[]);
  await page.evaluate(()=>initGame('LIGHT_SCOUT','Captain','Prospector'));
  await page.waitForFunction(()=>G?.galaxy && G.log.some(e=>e.msg.includes('Ready for departure')));
  await page.keyboard.press('i');for(let i=0;i<3;i++)await page.keyboard.press('ArrowRight');
